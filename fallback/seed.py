    while generated < target_clean_count and attempts < max_attempts:
        attempts += 1
        category = rng.choice(CLEAN_LOOP_CATEGORIES)
        candidates = [name for name, cat in VENDOR_POOL if cat == category] or [n for n, _ in VENDOR_POOL]
        vendor_name = rng.choice(candidates)
        when_date = rng.choice(all_days)
        when = datetime.combine(when_date, datetime.min.time()) + timedelta(
            hours=rng.randint(8, 18), minutes=rng.randint(0, 59)
        )

        cap = SOFT_THRESHOLD_CENTS if category in SOFT_THRESHOLD_CATEGORIES else HARD_THRESHOLD_CENTS
        amount_cents = rng.randint(3_000, int(cap * 0.85))

        if guard.collides(vendor_name, when_date, amount_cents, category):
            continue
        if velocity_guard.collides("agent_ops", when):
            continue

        warrant_id = warrant_for(category, when_date)
        insert_txn("agent_ops", warrant_id, vendor_name, category, amount_cents, when, False,
                   purposes_by_category[category])
        guard.record(vendor_name, when_date, amount_cents, category)
        generated += 1

    conn.commit()

    # === V1: hero duplicate =============================================
    # ACME Cloud Services LLC $4,080 (07-02, recurring) -> Accme Cloud Svcs
    # $4,200 (07-13, 11 days later). Misspelling lands the match in the
    # ambiguous [0.65, 0.90) band -- verified in tests/test_matcher.py.
