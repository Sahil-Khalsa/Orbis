        ("agent_vendor", "agent-vendor", "p_ben", "local:agent-vendor", "payee", "wallet_agent_vendor", "active"),
        ("agent_runaway", "agent-runaway", "p_alice", "local:agent-runaway", "spender", None, "active"),
