    insert_txn("agent_ops", w1, "ACME Cloud Services LLC", "infrastructure", 408_000,
               prior_when, True, "cloud hosting and infra services")
    guard.record("ACME Cloud Services LLC", prior_when.date(), 408_000, "infrastructure")

    dup_when = datetime(2026, 7, 13, 10, 5, 0)
    sr_dup = new_id("sr")
    t_dup = new_id("t")
    conn.execute(
        "INSERT INTO spend_requests VALUES (?,?,?,?,?,?,?,?,?,?,?)",
        (sr_dup, "agent_ops", w1, "bank", "Accme Cloud Svcs", None, "infrastructure",
         420_000, "cloud hosting and infra services", dup_when.isoformat(), "executed"),
    )
    conn.execute(
        "INSERT INTO transactions VALUES (?,?,?,?,?,?,?,?,?,?,?)",
        (t_dup, "bank", vendor_ids["ACME Cloud Services LLC"], None, "infrastructure", 420_000,
         dup_when.isoformat(), "cloud hosting and infra services", 0, f"pi_test_{t_dup}", sr_dup),
    )

    # === V2: non-recurring duplicate, 19 days apart, 3% amount diff =====
    v2_vendor = "Northgate Analytics Suite"
    v2_prior_when = datetime(2026, 4, 6, 11, 0, 0)
    insert_txn("agent_ops", w1, v2_vendor, "software", 200_000, v2_prior_when, False,
               "software license renewal")
    guard.record(v2_vendor, v2_prior_when.date(), 200_000, "software")

    v2_when = datetime(2026, 4, 25, 11, 30, 0)
    sr_v2 = new_id("sr")
    t_v2 = new_id("t")
    conn.execute(
        "INSERT INTO spend_requests VALUES (?,?,?,?,?,?,?,?,?,?,?)",
        (sr_v2, "agent_ops", w1, "bank", v2_vendor, None, "software",
         206_000, "software license renewal", v2_when.isoformat(), "executed"),
    )
    conn.execute(
        "INSERT INTO transactions VALUES (?,?,?,?,?,?,?,?,?,?,?)",
        (t_v2, "bank", vendor_ids[v2_vendor], None, "software", 206_000,
         v2_when.isoformat(), "software license renewal", 0, f"pi_test_{t_v2}", sr_v2),
    )

    # === V3: marketing budget breach, 148% of Q2 ========================
    # Steady spend to $17,000 committed (0.85 of $20,000, safely under the
    # 1.05 ROUTE threshold), then a single $12,600 transaction that jumps
    # straight past 1.20 to 1.48 -- no intermediate ROUTE-zone transaction.
    # Round-robin the full vendor pool (not just the 3 marketing-tagged
    # ones) so consecutive top-ups never land on the same vendor within
    # the 30-day/5% R4 window.
    q2_days = daterange_days(date(2026, 4, 1), date(2026, 6, 20))
    all_vendor_names = [n for n, _ in VENDOR_POOL]
    committed = 0
    step = 130_000  # ~$1,300 per top-up
    i = 0
    while committed < 1_700_000 and i < len(all_vendor_names) * 3:
        vendor_name = all_vendor_names[i % len(all_vendor_names)]
        when_date = q2_days[(i * 5) % len(q2_days)]
        when = datetime.combine(when_date, datetime.min.time()) + timedelta(hours=10 + i % 5)
        amount = min(step, 1_700_000 - committed)
        if amount < 50_000:
            amount = 50_000
        if guard.collides(vendor_name, when_date, amount, "marketing"):
            i += 1
            continue
        insert_txn("agent_ops", w2, vendor_name, "marketing", amount, when, False,
                   "marketing campaign spend")
        guard.record(vendor_name, when_date, amount, "marketing")
        committed += amount
        i += 1
    assert committed >= 1_700_000, f"V3 setup only reached {committed}c committed before giving up"

    v3_when = datetime(2026, 6, 25, 14, 0, 0)
    insert_txn("agent_ops", w2, "Prestige Worldwide Marketing", "marketing", 870_000, v3_when, False,
               "Q2 campaign push -- paid media placements")

    # === V4: unapproved vendor, never onboarded, $6,800 =================
    v4_when = datetime(2026, 5, 20, 9, 30, 0)
    sr_v4 = new_id("sr")
    conn.execute(
        "INSERT INTO spend_requests VALUES (?,?,?,?,?,?,?,?,?,?,?)",
        (sr_v4, "agent_ops", w1, "bank", "Redwood Data Partners", None, "other",
         680_000, "one-off data enrichment vendor", v4_when.isoformat(), "executed"),
    )
    # No `vendors` row exists for Redwood Data Partners -- never onboarded.
    # vendor_id is nullable, so the ledger entry just records no resolved
    # vendor rather than inventing a decoy row that would pollute the
    # fuzzy-matcher's candidate pool with a near-identical name.
    t_v4 = new_id("t")
    conn.execute(
        "INSERT INTO transactions VALUES (?,?,?,?,?,?,?,?,?,?,?)",
        (t_v4, "bank", None, None, "other", 680_000,
         v4_when.isoformat(), "one-off data enrichment vendor", 0, f"pi_test_{t_v4}", sr_v4),
    )

    # === V5: missing approval, above R6 hard threshold, no approval on file
    v5_when = datetime(2026, 3, 10, 15, 0, 0)
    insert_txn("agent_ops", w1, "Titan Hardware Solutions", "hardware", 530_000, v5_when, False,
               "bulk hardware refresh -- no human sign-off on file")
    guard.record("Titan Hardware Solutions", v5_when.date(), 530_000, "hardware")

    # === V6: velocity, 9 requests in 6 minutes ==========================
    burst_vendors = rng.sample([n for n, _ in VENDOR_POOL], 9)
    burst_start = datetime(2026, 5, 15, 10, 0, 0)
    for idx, vname in enumerate(burst_vendors):
        when = burst_start + timedelta(minutes=idx)
        amount = 1_000 + idx * 137
        if guard.collides(vname, when.date(), amount, "infrastructure"):
            amount += 500
        insert_txn("agent_runaway", w3, vname, "infrastructure", amount, when, False,
                   "burst infra top-up")
        guard.record(vname, when.date(), amount, "infrastructure")

    # === V7: expired warrant, charge 4 days after expiry ================
    v7_when = datetime(2026, 7, 4, 13, 0, 0)
    insert_txn("agent_ops", w2, "Halberd Consulting Group", "contractor", 190_000, v7_when, False,
               "contractor engagement -- stale warrant reference")
    guard.record("Halberd Consulting Group", v7_when.date(), 190_000, "contractor")

    conn.commit()

    # === Finalize live counters: warrants.spent_total_cents / budgets.committed_cents
    for wid in (w1, w2, w2b, w3, w4):
        row = conn.execute(
            """
            SELECT COALESCE(SUM(t.amount_cents), 0) AS total
            FROM transactions t JOIN spend_requests sr ON t.spend_request_id = sr.id
            WHERE sr.warrant_id = ?
            """,
            (wid,),
        ).fetchone()
        conn.execute("UPDATE warrants SET spent_total_cents = ? WHERE id = ?", (row["total"], wid))

    for (category, q_start), bid in budget_ids.items():
        q_end = next(e for s, e in QUARTERS if s == q_start)
        row = conn.execute(
            "SELECT COALESCE(SUM(amount_cents), 0) AS total FROM transactions "
            "WHERE category = ? AND occurred_at >= ? AND occurred_at <= ?",
            (category, q_start, q_end + "T23:59:59"),
        ).fetchone()
        conn.execute("UPDATE budgets SET committed_cents = ? WHERE id = ?", (row["total"], bid))

    conn.commit()
    conn.close()
    print(f"Seed complete: {generated} clean + 7 planted violations.")


