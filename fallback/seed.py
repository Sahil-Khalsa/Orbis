            "INSERT INTO transactions VALUES (?,?,?,?,?,?,?,?,?,?,?)",
            (txn_id, "bank", vendor_ids[vendor_name], None, category, amount_cents,
             when.isoformat(), purpose, 1 if recurring else 0, f"pi_test_{txn_id}", sr_id),
